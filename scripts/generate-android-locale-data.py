#!/usr/bin/env python3
"""Writes Android's locale data for choosing resources (LocaleDataTables.cpp) as Kotlin.

  scripts/generate-android-locale-data.py

Android chooses the strings of a resource directory (values-zh-rTW, values-b+sr+Latn, ...) with
these tables: likely scripts, region parents and representative locales, generated by AOSP from
ICU/CLDR. Source: AOSP platform/frameworks/base, libs/androidfw/LocaleDataTables.cpp at COMMIT
(android15-release, the Android version tests/integration compares with), Apache License 2.0.
a2ui-compat/.../android/content/res/ResourceLocales.kt is a port of the code that uses them.
"""
import base64, pathlib, re, urllib.request

import layout

ROOT = pathlib.Path(__file__).resolve().parent.parent
COMMIT = "cc8bb19595c661f5cf42f330457000e643c67d1b"
URL = f"https://android.googlesource.com/platform/frameworks/base/+/{COMMIT}/libs/androidfw/LocaleDataTables.cpp?format=TEXT"
CACHE = ROOT / "build" / "aosp" / f"LocaleDataTables-{COMMIT[:12]}.cpp"
OUT = layout.COMPAT / "src/commonMain/kotlin/ai/littlepress/a2ui/compat/android/content/res/LocaleDataTables.kt"


def source() -> str:
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_bytes(base64.b64decode(urllib.request.urlopen(URL).read()))
    return CACHE.read_text()


def block(text: str, name: str) -> str:
    # From the line after the declaration to the closing "};" or "});".
    match = re.search(rf"\b{re.escape(name)}\b[^\n]*\n(.*?)\n}}\)?;", text, flags=re.S)
    if not match:
        raise SystemExit(f"{name} not found in LocaleDataTables.cpp")
    return match.group(1)


def main() -> None:
    text = source()
    # Parse permissively (spacing, hex case, integer suffixes), and count each table's entries
    # independently of the entry syntax, by the hex numbers in it, so that no entry is skipped.
    hexnum = r"0[xX]([0-9A-Fa-f]+)[uUlL]*"
    whole = lambda n, per_entry: n // per_entry if n % per_entry == 0 else n / per_entry
    scripts = re.findall(r"\{\s*'(.)'\s*,\s*'(.)'\s*,\s*'(.)'\s*,\s*'(.)'\s*\}", block(text, "SCRIPT_CODES"))
    script_codes = ["".join(s) for s in scripts]
    likely = [(k.upper().zfill(8), v) for k, v in
              re.findall(rf"\{{\s*{hexnum}\s*,\s*(\d+)[uU]?\s*\}}", block(text, "LIKELY_SCRIPTS"))]
    representative = [v.upper().zfill(16) for v in re.findall(hexnum, block(text, "REPRESENTATIVE_LOCALES"))]
    parents, parent_counts = {}, {}
    script_parents = block(text, "SCRIPT_PARENTS")
    for *script, name in re.findall(r"\{\s*\{\s*'(.)'\s*,\s*'(.)'\s*,\s*'(.)'\s*,\s*'(.)'\s*\}\s*,\s*&(\w+)\s*\}", script_parents):
        table = block(text, name)
        entries = re.findall(rf"\{{\s*{hexnum}\s*,\s*{hexnum}\s*\}}", table)
        parents["".join(script)] = [(a.upper().zfill(8), b.upper().zfill(8)) for a, b in entries]
        numbers = len(re.findall(hexnum, table))
        parent_counts[name] = (len(entries), whole(numbers, 2))
    hex_count = lambda name: len(re.findall(hexnum, block(text, name)))
    expected = {
        "SCRIPT_CODES": (len(script_codes), whole(block(text, "SCRIPT_CODES").count("'"), 8)),
        "LIKELY_SCRIPTS": (len(likely), hex_count("LIKELY_SCRIPTS")),
        "REPRESENTATIVE_LOCALES": (len(representative), hex_count("REPRESENTATIVE_LOCALES")),
        "SCRIPT_PARENTS": (len(parents), script_parents.count("&")),
        **parent_counts,
    }
    depth = re.search(r"MAX_PARENT_DEPTH = (\d+);", text).group(1)
    # Every entry of each table must have been read.
    for name, (read, present) in expected.items():
        if read == 0 or read != present:
            raise SystemExit(f"{name}: read {read} of {present} entries; has LocaleDataTables.cpp's format changed?")

    lines = [
        "package ai.littlepress.a2ui.compat.android.content.res",
        "",
        "// Generated by scripts/generate-android-locale-data.py from AOSP platform/frameworks/base",
        f"// libs/androidfw/LocaleDataTables.cpp at {COMMIT}, Apache License 2.0. Do not edit.",
        "// Packed values as there: language and region of two bytes each, see ResourceLocales.",
        "",
        "/** Four-letter script codes; LIKELY_SCRIPTS refers to them by index. */",
        f'internal const val SCRIPT_CODES: String = "{"".join(script_codes)}"',
        "",
        "/** Packed language (and region) -> index in SCRIPT_CODES: 8 + 2 hex digits per entry. */",
        "internal const val LIKELY_SCRIPTS: String =",
    ]
    lines += chunks([f"{key}{int(index):02X}" for key, index in likely])
    lines += [
        "",
        "/** Packed language, region and script of representative locales: 16 hex digits per entry. */",
        "internal const val REPRESENTATIVE_LOCALES: String =",
    ]
    lines += chunks(representative)
    lines += ["", "/** Script -> packed locale and its parent, 8 + 8 hex digits per entry. */",
              "internal val SCRIPT_PARENTS: Map<String, String> = mapOf("]
    for script, entries in parents.items():
        lines.append(f'    "{script}" to')
        lines += ["    " + line for line in chunks([a + b for a, b in entries])]
        lines[-1] += ","
    lines += [")", "", f"internal const val MAX_PARENT_DEPTH: Int = {depth}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(script_codes)} scripts, {len(likely)} likely scripts, "
          f"{len(representative)} representative locales, {sum(map(len, parents.values()))} parents")


def chunks(entries: list, per_line: int = 6) -> list:
    rows = ["".join(entries[i:i + per_line]) for i in range(0, len(entries), per_line)]
    return [f'    "{row}"' + (" +" if i < len(rows) - 1 else "") for i, row in enumerate(rows)]


if __name__ == "__main__":
    main()
