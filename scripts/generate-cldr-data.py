#!/usr/bin/env python3
"""Writes the Unicode CLDR data that a2ui-compat needs as Kotlin.

  scripts/generate-cldr-data.py [CLDR version, default 45]

CLDR 45 is the version in ICU 75.1, which an Android 15 (API 35) emulator reports. Data: Unicode CLDR (cldr-json),
Unicode License v3. Downloads into build/cldr.
- Cardinal and ordinal plural rules (supplemental/plurals.json, ordinals.json), for MessageFormat on
  desktop and iOS.
"""
import json, pathlib, sys, urllib.request

import layout

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSION = sys.argv[1] if len(sys.argv) > 1 else "45"
CACHE = ROOT / "build" / "cldr"
COMPAT = layout.COMPAT / "src"
HEADER = [
    f"// Generated by scripts/generate-cldr-data.py from Unicode CLDR {VERSION} (cldr-json),",
    "// Unicode License v3. Do not edit.",
    "",
]


def download(name: str, url: str) -> bytes:
    path = CACHE / name
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        path.write_bytes(urllib.request.urlopen(url).read())
    return path.read_bytes()


def plural_rules() -> None:
    out = ["package ai.littlepress.a2ui.compat.android.icu.text", "", *HEADER]
    for kind, name in (("cardinal", "CLDR_PLURAL_RULES"), ("ordinal", "CLDR_ORDINAL_RULES")):
        file = "plurals" if kind == "cardinal" else "ordinals"
        raw = download(f"{file}-{VERSION}.json",
                       f"https://raw.githubusercontent.com/unicode-org/cldr-json/{VERSION}.0.0/cldr-json/cldr-core/supplemental/{file}.json")
        rules = json.loads(raw)["supplemental"][f"plurals-type-{kind}"]
        out += [f"/** Locale -> {kind} plural category -> rule, without samples. */",
                f"internal val {name}: Map<String, Map<String, String>> = mapOf("]
        for locale in sorted(rules):
            entries = [f'"{key.removeprefix("pluralRule-count-")}" to "{rule.split("@")[0].strip()}"'
                       for key, rule in rules[locale].items()]
            out.append(f'    "{locale}" to mapOf({", ".join(entries)}),')
        out += [")", ""]
        print(f"{kind} plural rules: {len(rules)} locales")
    (COMPAT / "commonMain/kotlin/ai/littlepress/a2ui/compat/android/icu/text/CldrPluralRules.kt").write_text("\n".join(out))


plural_rules()
