#!/usr/bin/env python3
"""Per-package file statistics for the changelog: how each upstream Kotlin source file is built.

  as-is      compiled for every platform exactly as synced
  generated  replaced by an overlay that scripts/generate-overlays.py writes (listed rules only)
  hand-made  replaced by a hand-written file at the same path in <module>/overlay-manual
  not built  the package has no KMP module yet

Run directly to print the tables for the current tree.
"""
import collections, json, pathlib

import layout

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGES = [  # (upstream package, its main sources, KMP module or None)
    ("a2ui-model", "source/a2ui/a2ui-model/src/main/kotlin", "a2ui-model"),
    ("a2ui-engine", "source/a2ui/a2ui-engine/src/main/kotlin", "a2ui-engine"),
    ("compose-runtime", "source/a2ui/compose/compose-runtime/src/main/kotlin", "compose-runtime"),
    ("compose-ui", "source/a2ui/compose/compose-ui/src/main/kotlin", "compose-ui"),
    ("compose-ui-testing", "source/a2ui/compose/compose-ui-testing/src/main/kotlin", "compose-ui-testing"),
    ("material3-a2ui", "source/material3-a2ui/src/main/kotlin", "material3-a2ui"),
]


def package_stats():
    rows, rules = [], collections.Counter()
    for name, sources, module in PACKAGES:
        files = sorted(p.relative_to(ROOT / sources).as_posix() for p in (ROOT / sources).rglob("*.kt"))
        if module is None:
            rows.append((name, len(files), 0, 0, 0, len(files)))
            continue
        mod = layout.MODULES[module]
        manifest = json.loads((mod / "overlay-generated.json").read_text())
        manual = mod / "overlay-manual"
        hand = [f for f in files if (manual / f).exists()]
        generated = [f for f in files if f in manifest and f not in hand]
        for f in generated:
            rules.update(manifest[f]["rules"])
        rows.append((name, len(files), len(files) - len(hand) - len(generated), len(generated), len(hand), 0))
    return rows, rules


def is_generated(path: pathlib.Path) -> bool:
    """A data file a script writes or a test records (said so in its header)."""
    head = "\n".join(path.read_text().splitlines()[:6])
    return any(marker in head for marker in ("Generated by", "Recorded by", "Recorded from"))


def compat_stats():
    """Our own adapter code, by source set: hand-written files and lines, generated files and lines."""
    out = []
    for source_set in ("commonMain", "desktopMain", "iosMain"):
        files = list((layout.COMPAT / "src" / source_set).rglob("*.kt"))
        written = [f for f in files if not is_generated(f)]
        generated = [f for f in files if is_generated(f)]
        lines = lambda group: sum(len(f.read_text().splitlines()) for f in group)
        out.append((source_set, len(written), lines(written), len(generated), lines(generated)))
    return out


def module_stats():
    """Our code inside modules (src/commonMain), and code generated from upstream resources, by
    module: (module, own files, own lines, generated files, generated lines)."""
    out = []
    for name, sources, module in PACKAGES:
        if module is None:
            continue
        mod = layout.MODULES[module]
        own = list((mod / "src" / "commonMain" / "kotlin").rglob("*.kt"))
        generated = list((mod / "resources-generated").rglob("*.kt"))
        if own or generated:
            lines = lambda files: sum(len(f.read_text().splitlines()) for f in files)
            out.append((module, len(own), lines(own), len(generated), lines(generated)))
    return out


def markdown() -> str:
    rows, rules = package_stats()
    lines = [
        "| Package | Kotlin files | As-is | Generated overlay | Hand-made overlay | Not built yet | Built for KMP |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]

    def share(counts):
        files, built = counts[0], counts[0] - counts[4]
        return f"{built}/{files} ({100 * built / files:.1f}%)" if files else "-"

    total = [0] * 5
    for name, *counts in rows:
        lines.append(f"| {name} | " + " | ".join(str(c) for c in counts) + f" | {share(counts)} |")
        total = [t + c for t, c in zip(total, counts)]
    lines.append("| **Total** | " + " | ".join(f"**{c}**" for c in total) + f" | **{share(total)}** |")
    lines += ["", "Generated overlays by rule (a file can have several):", ""]
    lines += [f"- `{rule}`: {count}" for rule, count in sorted(rules.items())]
    compat = compat_stats()
    lines += ["", "Our adapter code (`a2ui-compat`, in `target/a2ui-kmp`), which the overlays import, maintained by us (and data our",
              "scripts generate or record, not edited by hand):", ""]
    for source_set, files, loc, data_files, data_loc in compat:
        data = f" (+ {data_files} data files, {data_loc} lines)" if data_files else ""
        lines.append(f"- {source_set}: {files} files, {loc} lines{data}")
    data_total = sum(c[3] for c in compat), sum(c[4] for c in compat)
    lines.append(f"- total: {sum(c[1] for c in compat)} files, {sum(c[2] for c in compat)} lines"
                 + (f" (+ {data_total[0]} data files, {data_total[1]} lines)" if data_total[0] else ""))
    modules = module_stats()
    if modules:
        lines += ["", "In the modules, besides overlays:", ""]
        for module, own, own_lines, generated, generated_lines in modules:
            parts = []
            if own:
                parts.append(f"{own} files, {own_lines} lines of ours")
            if generated:
                parts.append(f"{generated} files, {generated_lines} lines generated from upstream resources")
            lines.append(f"- {module}: " + "; ".join(parts))
    return "\n".join(lines)


if __name__ == "__main__":
    print(markdown())
